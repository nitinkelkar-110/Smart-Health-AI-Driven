/**
 * Simple script-based language heuristic
 */
export function detectScriptAndLanguage(text: string): string {
  if (!text) return 'en';

  // Devanagari script: Marathi / Hindi
  if (/[\u0900-\u097F]/.test(text)) {
    if (text.includes('आहे') || text.includes('नाही') || text.includes('केंद्रात') || text.includes('साठा')) {
      return 'mr';
    }
    return 'hi';
  }

  // Arabic / Perso-Arabic script: Arabic / Urdu / Persian
  if (/[\u0600-\u06FF]/.test(text)) {
    if (text.includes('ہے') || text.includes('میں') || text.includes('کیا')) {
      return 'ur';
    }
    return 'ar';
  }

  // Bengali script
  if (/[\u0980-\u09FF]/.test(text)) return 'bn';
  // Tamil script
  if (/[\u0B80-\u0BFF]/.test(text)) return 'ta';
  // Telugu script
  if (/[\u0C00-\u0C7F]/.test(text)) return 'te';
  // Gujarati script
  if (/[\u0A80-\u0AFF]/.test(text)) return 'gu';
  // Kannada script
  if (/[\u0C80-\u0CFF]/.test(text)) return 'kn';
  // Malayalam script
  if (/[\u0D00-\u0D7F]/.test(text)) return 'ml';
  // Gurmukhi (Punjabi)
  if (/[\u0A00-\u0A7F]/.test(text)) return 'pa';
  // Han (Chinese)
  if (/[\u4E00-\u9FFF]/.test(text)) return 'zh';
  // Japanese Kana
  if (/[\u3040-\u30FF]/.test(text)) return 'ja';
  // Korean Hangul
  if (/[\uAC00-\uD7AF]/.test(text)) return 'ko';
  // Cyrillic (Russian, Ukrainian)
  if (/[\u0400-\u04FF]/.test(text)) return 'ru';
  // Hebrew
  if (/[\u0590-\u05FF]/.test(text)) return 'he';

  return 'en';
}
