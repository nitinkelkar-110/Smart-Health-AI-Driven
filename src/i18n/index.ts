/**
 * Returns localized string dictionary based on active language code.
 * Falls back cleanly to English if specific language dictionary is missing.
 */
export function getTranslation(lang: string): TranslationSet {
  if (!lang) return translations.en;
  const normalized = lang.toLowerCase().trim();
  if (translations[normalized]) {
    return translations[normalized];
  }
  const base = normalized.split('-')[0];
  if (translations[base]) {
    return translations[base];
  }
  return translations.en;
}
