/**
 * Live Dynamic Discovery Function:
 * Fetches real model lists from OpenRouter public API, Ollama localhost, etc.
 */
export async function discoverLiveProviderModels(
  provider: AIProviderName,
  baseUrl?: string,
  apiKey?: string
): Promise<AIModel[]> {
  try {
    if (provider === 'OpenRouter') {
      const res = await fetch('https://openrouter.ai/api/v1/models', {
        headers: apiKey ? { Authorization: `Bearer ${apiKey}` } : {},
      });
      if (res.ok) {
        const json = await res.json();
        const data: any[] = json.data || [];
        
        // Filter models with pricing prompt: "0" or completion: "0" or ending with :free
        const freeDiscovered = data.filter((m) => {
          const isFreeId = m.id && m.id.endsWith(':free');
          const isZeroPrice = m.pricing && (m.pricing.prompt === '0' || m.pricing.prompt === 0);
          return isFreeId || isZeroPrice;
        });

        return freeDiscovered.map((m) => ({
          id: `discovered-or-${m.id.replace(/[\/:]/g, '-')}`,
          provider: 'OpenRouter' as const,
          modelId: m.id,
          displayName: `${m.name || m.id} (Live Discovered)`,
          description: m.description || 'Live model discovered from OpenRouter free registry.',
          freeEligibility: 'FREE_TIER_API' as const,
          pricingStatus: 'Free Tier Verified ($0.00)',
          isFreeOnlyEligible: true,
          contextWindow: m.context_length || 32768,
          modalities: ['text'],
          supportedTasks: ['chat', 'healthcare'],
          supportedLanguages: ['multilingual'],
          toolCalling: true,
          streaming: true,
          status: 'AVAILABLE' as const,
          rateLimitNote: 'Dynamic provider rate limit',
          estimatedLatencyMs: 350,
          lastVerified: new Date().toISOString().split('T')[0],
        }));
      }
    } else if (provider === 'Ollama') {
      const url = (baseUrl || 'http://localhost:11434') + '/api/tags';
      const res = await fetch(url);
      if (res.ok) {
        const json = await res.json();
        const models: any[] = json.models || [];
        return models.map((m) => ({
          id: `discovered-ollama-${m.name.replace(/[:.]/g, '-')}`,
          provider: 'Ollama' as const,
          modelId: m.name,
          displayName: `Local: ${m.name}`,
          description: `Locally installed model on this machine. Size: ${(m.size / 1e9).toFixed(1)} GB.`,
          freeEligibility: 'PERMANENTLY_FREE_LOCAL' as const,
          pricingStatus: 'Permanently Free (Local)',
          isFreeOnlyEligible: true,
          contextWindow: 32768,
          modalities: ['text'],
          supportedTasks: ['chat', 'reasoning', 'healthcare'],
          supportedLanguages: ['multilingual', 'en', 'hi', 'mr'],
          toolCalling: true,
          streaming: true,
          status: 'AVAILABLE' as const,
          rateLimitNote: 'Uncapped local inference',
          estimatedLatencyMs: 90,
          lastVerified: new Date().toISOString().split('T')[0],
        }));
      }
    }
  } catch (err) {
    console.warn(`Dynamic model discovery for ${provider} failed or endpoint offline:`, err);
  }
  return [];
}
